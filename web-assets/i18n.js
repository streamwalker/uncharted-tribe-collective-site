  var KEY = 'utc-lang';

  function dirFor(code){
    for (var i=0;i<LANGS.length;i++) if (LANGS[i].code===code) return LANGS[i].dir;
    return 'ltr';
  }

  function apply(code){
    var dict = T[code] || T.en;
    var fallback = T.en;
    document.querySelectorAll('[data-i18n]').forEach(function(el){
      var k = el.getAttribute('data-i18n');
      var v = dict[k] || fallback[k];
      if (v != null) el.textContent = v;
    });
    document.querySelectorAll('[data-i18n-aria]').forEach(function(el){
      var k = el.getAttribute('data-i18n-aria');
      var v = dict[k] || fallback[k];
      if (v != null) el.setAttribute('aria-label', v);
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(function(el){
      var k = el.getAttribute('data-i18n-placeholder');
      var v = dict[k] || fallback[k];
      if (v != null) el.setAttribute('placeholder', v);
    });
    /* newsletter success label is set by inline JS — keep it localised */
    w.__utcWelcome = dict.news_welcome || fallback.news_welcome;
    var dir = dirFor(code);
    document.documentElement.setAttribute('lang', code);
    document.documentElement.setAttribute('dir', dir);
    try { localStorage.setItem(KEY, code); } catch(e){}
  }

  function stored(){
    try { var s = localStorage.getItem(KEY); if (s && T[s]) return s; } catch(e){}
    var nav = (navigator.language || 'en').slice(0,2).toLowerCase();
    return T[nav] ? nav : 'en';
  }

  function init(){
    var sel = document.getElementById('langSel');
    if (sel){
      LANGS.forEach(function(l){
        var o = document.createElement('option');
        o.value = l.code; o.textContent = l.label;
        sel.appendChild(o);
      });
      var cur = stored();
      sel.value = cur;
      apply(cur);
      sel.addEventListener('change', function(){ apply(sel.value); });
    } else {
      apply(stored());
    }
  }

  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', init);
  else init();

